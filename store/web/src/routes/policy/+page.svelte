	<p class="eyebrow dim">For publishers</p>
	<h1>Content policy</h1>
	<p class="dim lead">People install store apps on their own Hamstr, often for family and friends. Publish apps you would hand to them yourself.</p>

	<section class="section">
		<h2>Not allowed</h2>
		<ul class="steps policy-list">
			<li><strong>Phishing and impersonation.</strong> No apps that pose as a bank, a brand or another service, and no apps that ask for another service's passwords, card numbers, recovery phrases or private keys.</li>
			<li><strong>Malware.</strong> No cryptocurrency mining, hidden or deliberately obfuscated code, attacks on the visitor's device or network, or code loaded from elsewhere to change the app after review.</li>
			<li><strong>Tracking.</strong> No analytics, ad or tracking scripts, and no sending people's data anywhere the listing does not say. Ask for network access only for what the app does.</li>
			<li><strong>Scams and spam.</strong> No fake prizes, investment schemes, deceptive offers or apps that exist to advertise.</li>
			<li><strong>Illegal or hateful content.</strong> No sexual content involving minors, nothing illegal, no hate, harassment or threats. No sexual content at all, for now.</li>
			<li><strong>Misleading listings.</strong> The name, summary and description say what the app does. No borrowed names or logos.</li>
			<li><strong>Impersonating publishers.</strong> Your publisher name is part of every app's address (<code>you/app</code>). Names that copy a brand, the store or another publisher are refused or reviewed.</li>
		</ul>
	</section>

	<section class="section">
		<h2>How review works</h2>
		<ul class="steps policy-list">
			<li>Automatic checks read every release's pages and code when it arrives. They never run it.</li>
			<li>An update that asks for new internet access, or one published right after a password change or with a new token, always waits for a person.</li>
			<li>On a Hamstr, an app's pages can only load code from the app itself and talk to the hosts its listing declares.</li>
			<li>A person reviews new releases before they appear in the catalog. Some may be held or blocked automatically; a moderator looks at every one of those too.</li>
			<li>If a release is rejected, your <a href="/account">account page</a> says why. Fix it and publish a new version.</li>
			<li>Anyone can report a release. Moderators can take a release down, and suspend an account that breaks these rules, which hides all of its apps.</li>
		</ul>
	</section>

	<section class="section">
		<h2>Your account</h2>
		<p>An account exists only to publish. It has a name and a password: no email, no tracking. Keep the password safe, since there is no reset yet.</p>
	</section>
