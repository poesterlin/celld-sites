#!/bin/sh
# Build an EmDash site (Astro + @astrojs/cloudflare, e.g. a checkout of an
# emdash-playground branch) for celld and deploy it, with its CMS editor at
# https://<hostname>/_emdash/admin:
#   tools/deploy-emdash.sh <checkout> <hostname> [--extra-assets DIR] [push.sh options]
# The checkout needs its dependencies installed (bun install). This script adds
# celld-adapter/, astro.celld.config.mjs and celld.json to it and rebuilds dist/.
#
# The build is the site's own astro.config.mjs with one change: the database is
# EmDash's Durable Object adapter instead of D1 (see adapters/emdash/). Media
# uploads and sessions are stored in Durable Objects too. Redeploying changes
# code only; the CMS content belongs to the site and stays.
#
# On a site's first deploy EmDash still needs setup. This applies the site's
# seed (setup wizard step 1, content included); the first visit to
# /_emdash/admin then asks for the admin's name and email and a passkey. Until
# someone does that, anyone who can reach the hostname can claim the admin.
#
# --extra-assets DIR adds the files in DIR to the static files (existing build
# files win), e.g. media a previous static export served.
set -eu
usage="usage: tools/deploy-emdash.sh <checkout> <hostname> [--extra-assets DIR] [push.sh options]"
site=$(cd "${1:?$usage}" && pwd)
host="${2:?$usage}"
shift 2
extra=
if [ "${1:-}" = "--extra-assets" ]; then
	extra=$(cd "${2:?$usage}" && pwd)
	shift 2
fi
project="${CELLD_COMPOSE_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
compose() { docker compose --project-directory "$project" "$@"; }

[ -f "$site/astro.config.mjs" ] || { echo "deploy-emdash: $site has no astro.config.mjs" >&2; exit 1; }
[ -x "$site/node_modules/.bin/astro" ] || { echo "deploy-emdash: dependencies missing, run bun install in $site" >&2; exit 1; }

rm -rf "$site/celld-adapter"
mkdir "$site/celld-adapter"
cp "$project/adapters/emdash/entry.mjs" "$project/adapters/emdash/objects.mjs" "$site/celld-adapter/"

# Same config, Durable Object database. Refuse a config this doesn't recognise
# rather than build a site that would look for a D1 binding.
node -e '
const fs = require("node:fs");
const [src, out] = process.argv.slice(1);
let config = fs.readFileSync(src, "utf8");
const steps = [
	[/import\s*\{([^}]*)\}\s*from\s*"@emdash-cms\/cloudflare";/, (m, names) =>
		`import { ${[...new Set([...names.split(",").map((n) => n.trim()).filter((n) => n && n !== "d1"), "durableObjects"])].join(", ")} } from "@emdash-cms/cloudflare";`],
	[/database:\s*d1\(\{[^}]*\}\)/, () => `database: durableObjects({ binding: "DB_DO" })`],
];
for (const [pattern, replace] of steps) {
	if (!pattern.test(config)) { console.error(`deploy-emdash: astro.config.mjs does not match ${pattern}`); process.exit(1); }
	config = config.replace(pattern, replace);
}
fs.writeFileSync(out, "// Generated by celld-sites tools/deploy-emdash.sh from astro.config.mjs.\n" + config);
' "$site/astro.config.mjs" "$site/astro.celld.config.mjs"

# EmDash 0.36 builds content URLs from a collection's `urlPattern` and falls
# back to /<collection>/<slug> without one, while these sites serve pages at
# /<slug>. Give every collection the pattern the site's route actually uses, in
# the seed: a site's first deploy copies it into the database.
seed_patched=
if [ -f "$site/seed/seed.json" ]; then
	node -e '
const fs = require("node:fs");
const file = process.argv[1];
const seed = JSON.parse(fs.readFileSync(file, "utf8"));
let changed = false;
for (const collection of seed.collections ?? []) {
	if (collection.urlPattern) continue;
	collection.urlPattern = "/{slug}";
	changed = true;
}
if (changed) fs.writeFileSync(file, JSON.stringify(seed, null, "\t") + "\n"), process.exit(0);
process.exit(1);
' "$site/seed/seed.json" && seed_patched=1
fi
restore_seed() {
	[ -n "$seed_patched" ] || return 0
	if git -C "$site" rev-parse --git-dir >/dev/null 2>&1; then
		git -C "$site" checkout -- seed/seed.json 2>/dev/null || true
	fi
	seed_patched=
}

echo "deploy-emdash: building $site" >&2
log="$site/celld-adapter/build.log"
if ! (cd "$site" && ASTRO_TELEMETRY_DISABLED=1 NODE_ENV=production node node_modules/.bin/astro build --config astro.celld.config.mjs) >"$log" 2>&1; then
	tail -30 "$log" >&2
	echo "deploy-emdash: astro build failed, full log in $log" >&2
	restore_seed
	exit 1
fi
restore_seed

# The workerd compatibility date the site was built for.
node -e '
const fs = require("node:fs");
const [adapter, wrangler, out] = process.argv.slice(1);
const config = JSON.parse(fs.readFileSync(adapter, "utf8"));
const date = JSON.parse(fs.readFileSync(wrangler, "utf8")).compatibility_date;
if (/^\d{4}-\d{2}-\d{2}$/.test(date ?? "")) config.compatibilityDate = date;
fs.writeFileSync(out, JSON.stringify(config, null, "\t") + "\n");
' "$project/adapters/emdash/celld.json" "$site/dist/server/wrangler.json" "$site/celld.json"

if [ -n "$extra" ]; then
	cp -R --update=none "$extra/." "$site/dist/client/"
fi

bundle=$(mktemp -d)
trap 'rm -rf "$bundle"' EXIT
node "$project/tools/pack.mjs" "$site" "$bundle"
tar -C "$bundle" -cf - . | compose exec -T celld /app/push.sh "$host" "$@"

# First deploy: apply the seed (setup step 1). Requests go to the node inside the
# container with the site's hostname, as Traefik would send them, so this works
# before the hostname is routed and EmDash records https://<hostname> as its URL.
site_request() {
	compose exec -T celld curl -sS --max-time 120 -H "Host: $host" -H "X-Forwarded-Proto: https" -H "Origin: https://$host" "$@"
}
status=$(site_request "http://127.0.0.1:8080/_emdash/api/setup/status")
body=$(printf '%s' "$status" | node -e '
let input = "";
process.stdin.on("data", (d) => (input += d)).on("end", () => {
	const status = JSON.parse(input);
	if (!status.success) { console.error(`deploy-emdash: setup status failed: ${input.slice(0, 300)}`); process.exit(1); }
	const { needsSetup, step, seedInfo = {} } = status.data;
	if (!needsSetup || step !== "start") return;
	process.stdout.write(JSON.stringify({ title: seedInfo.title || process.argv[1], tagline: seedInfo.tagline || "", includeContent: true }));
});
' "$host")
if [ -z "$body" ]; then
	echo "deploy-emdash: $host is already set up, content unchanged" >&2
else
	result=$(printf '%s' "$body" | site_request -X POST -H "Content-Type: application/json" --data-binary @- "http://127.0.0.1:8080/_emdash/api/setup")
	case "$result" in
	*'"success":true'*) echo "deploy-emdash: applied the seed; finish setup at https://$host/_emdash/admin" >&2 ;;
	*) echo "deploy-emdash: seeding failed: $(printf '%s' "$result" | head -c 400)" >&2; exit 1 ;;
	esac
fi
